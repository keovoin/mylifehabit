let currentLang = localStorage.getItem('healthApp_lang') || 'en';

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('healthApp_lang', lang);

    // Update button states
    document.querySelectorAll('.lang-btn, .lang-btn-sm').forEach(btn => {
        btn.classList.toggle('active', btn.textContent.trim() === (lang === 'en' ? 'EN' : 'ខ្មែរ'));
    });

    // Set font
    document.body.style.fontFamily = lang === 'kh'
        ? "'Noto Sans Khmer', 'Inter', sans-serif"
        : "'Inter', sans-serif";

    // Translate all elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (TRANSLATIONS[lang][key]) {
            el.textContent = TRANSLATIONS[lang][key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (TRANSLATIONS[lang][key]) {
            el.placeholder = TRANSLATIONS[lang][key];
        }
    });
}

function t(key) {
    return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) || TRANSLATIONS.en[key] || key;
}
